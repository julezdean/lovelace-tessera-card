/**
 * Generates tools/demo/icons.js - the MDI paths the demo harness needs.
 * Run after adding an icon to a demo scene:  node tools/build-demo-icons.js
 */
import { writeFileSync, readFileSync } from 'node:fs';
import * as mdi from '@mdi/js';

const html = readFileSync(new URL('./demo/index.html', import.meta.url), 'utf8');
const names = [...new Set(html.match(/mdi:[a-z0-9-]+/g) || [])];

const toKey = (name) =>
  'mdi' + name.slice(4).split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

const icons = {};
const missing = [];
for (const name of names.sort()) {
  const path = mdi[toKey(name)];
  if (path) icons[name] = path;
  else missing.push(name);
}

writeFileSync(
  new URL('./demo/icons.js', import.meta.url),
  `// Generated by tools/build-demo-icons.js - do not edit.\nexport const ICONS = ${JSON.stringify(icons, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(icons).length} icons`);
if (missing.length) console.warn('missing:', missing.join(', '));
